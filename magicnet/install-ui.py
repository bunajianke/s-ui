#!/usr/bin/env python3
"""Install a pinned frontend without modifying S-UI's binary, database, or unit.

Run as root after building frontend/dist. Requires an existing Nginx proxy
location for the database's webPath. No runtime settings are stored in Git.
"""
import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import re
import shutil
import sqlite3
import subprocess


def locations(base, current, port):
    headers = """
    proxy_set_header Host $http_host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $remote_addr;
    proxy_set_header X-Forwarded-Proto https;
    proxy_cookie_flags ~ secure httponly samesite=strict;
    proxy_read_timeout 60s;
    client_max_body_size 16m;
"""
    return f"""# Generated by MagicNet install-ui.py; keep this file private.
location = /_magicnet_session_check {{
    internal;
    access_log off;
    proxy_pass http://127.0.0.1:{port}{base}api/changes;
    proxy_pass_request_body off;
    proxy_set_header Content-Length "";
    proxy_set_header X-Requested-With XMLHttpRequest;
    proxy_set_header Cookie $http_cookie;
    proxy_set_header Host $http_host;
}}
location ^~ {base}api/ {{
    proxy_pass http://127.0.0.1:{port};
    {headers}
}}
location ^~ {base}apiv2/ {{
    proxy_pass http://127.0.0.1:{port};
    {headers}
}}
location ^~ {base}assets/ {{
    alias {current}/assets/;
    autoindex off;
    add_header Cache-Control "public, max-age=31536000, immutable";
    add_header X-Content-Type-Options nosniff always;
}}
location = {base}login {{
    alias {current}/index.html;
    default_type text/html;
    add_header Cache-Control "private, no-store" always;
    add_header X-Frame-Options SAMEORIGIN always;
    add_header Referrer-Policy no-referrer always;
}}
location = {base}_magicnet-index.html {{
    internal;
    auth_request /_magicnet_session_check;
    error_page 401 = @magicnet_login;
    alias {current}/index.html;
    default_type text/html;
    add_header Cache-Control "private, no-store" always;
    add_header X-Frame-Options SAMEORIGIN always;
    add_header Referrer-Policy no-referrer always;
}}
location @magicnet_login {{ return 302 {base}login; }}
location = {base.rstrip('/')} {{ return 302 {base}; }}
location ^~ {base} {{ rewrite ^ {base}_magicnet-index.html last; }}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dist', type=Path, required=True)
    parser.add_argument('--release', required=True, help='pinned frontend Git commit')
    parser.add_argument('--db', type=Path, default=Path('/var/lib/s-ui/s-ui.db'))
    parser.add_argument('--site', type=Path, default=Path('/etc/nginx/sites-available/default'))
    parser.add_argument('--root', type=Path, default=Path('/opt/magicnet-sui/ui'))
    parser.add_argument('--include', type=Path, default=Path('/etc/cloudcone-panel/magicnet-ui.locations.conf'))
    args = parser.parse_args()
    if os.geteuid() != 0:
        parser.error('run as root')
    if not re.fullmatch(r'[a-zA-Z0-9._-]{7,64}', args.release):
        parser.error('invalid release name')
    for path in (args.root, args.include):
        if not re.fullmatch(r'/[a-zA-Z0-9/._-]+', str(path)):
            parser.error('unsafe Nginx filesystem path')
    if not (args.dist / 'index.html').is_file() or not (args.dist / 'assets').is_dir():
        parser.error('expected a built frontend/dist directory')
    with sqlite3.connect(f'file:{args.db}?mode=ro', uri=True) as conn:
        settings = dict(conn.execute('select key,value from settings'))
    base = settings.get('webPath', '/app/')
    port = int(settings.get('webPort', 2095))
    if not re.fullmatch(r'/[a-zA-Z0-9/_-]+/', base):
        parser.error('unsupported webPath; review Nginx routing manually')
    site = args.site.resolve()
    previous_site = site.read_text()
    include_line = f'include {args.include};'
    if include_line not in previous_site:
        pattern = r'location\s+\^~\s+' + re.escape(base) + r'\s*\{[^{}]*\}'
        next_site, count = re.subn(pattern, include_line, previous_site)
        if not count:
            parser.error('no matching existing panel proxy location; no changes made')
    else:
        next_site = previous_site
    release = args.root / 'releases' / args.release
    current = args.root / 'current'
    previous_link = os.readlink(current) if current.is_symlink() else None
    if current.exists() and not current.is_symlink():
        parser.error('current must be a symlink')
    previous_include = args.include.read_bytes() if args.include.exists() else None
    backup = args.root / 'backups' / datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')
    backup.mkdir(parents=True, mode=0o700)
    os.chmod(backup.parent, 0o700)
    (backup / 'nginx-site').write_text(previous_site)
    if previous_include is not None:
        (backup / 'nginx-include').write_bytes(previous_include)
    (backup / 'state.json').write_text(json.dumps({
        'site': str(site), 'include': str(args.include), 'current': str(current),
        'previous_link': previous_link,
    }))
    if release.exists():
        parser.error('release already exists; use a unique pinned release identifier')
    shutil.copytree(args.dist, release)
    # Only deployment substitutes the private base path into the generic build.
    index = release / 'index.html'
    html = index.read_text()
    if '{{ .BASE_URL }}' not in html:
        parser.error('BASE_URL template missing; review build before installing')
    index.write_text(html.replace('{{ .BASE_URL }}', base))
    for item in [release, *release.rglob('*')]:
        os.chmod(item, 0o755 if item.is_dir() else 0o644)
    args.include.parent.mkdir(parents=True, exist_ok=True)
    try:
        staged = args.root / 'current.next'
        staged.unlink(missing_ok=True)
        staged.symlink_to('releases/' + args.release)
        staged.replace(current)
        args.include.write_text(locations(base, current, port))
        os.chmod(args.include, 0o600)
        site.write_text(next_site)
        subprocess.run(['nginx', '-t'], check=True)
        subprocess.run(['systemctl', 'reload', 'nginx'], check=True)
    except Exception:
        site.write_text(previous_site)
        if previous_include is None:
            args.include.unlink(missing_ok=True)
        else:
            args.include.write_bytes(previous_include)
        current.unlink(missing_ok=True)
        if previous_link:
            current.symlink_to(previous_link)
        subprocess.run(['nginx', '-t'], check=False)
        subprocess.run(['systemctl', 'reload', 'nginx'], check=False)
        raise
    print(json.dumps({'release': args.release, 'rollback_snapshot': str(backup)}))


if __name__ == '__main__':
    main()
